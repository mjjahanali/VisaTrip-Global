/**
 * Generates src/data/catalogSummary.ts from the full content modules
 * (services.ts, destinations.ts, packages.ts, blogs.ts).
 *
 * Keeps Homepage, Navbar, Footer, CinematicHero, and leadContext lightweight
 * (~12 KB raw instead of ~282 KB of full detail articles, itineraries, and FAQs).
 *
 * Run with: npx tsx scripts/generate-catalog-summary.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { servicesData } from '../src/data/services.ts';
import { destinationsData } from '../src/data/destinations.ts';
import { tourPackagesData } from '../src/data/packages.ts';
import { blogPostsData } from '../src/data/blogs.ts';

const serviceSummaries = servicesData.map((s) => ({
  slug: s.slug,
  icon: s.icon,
  theme: s.theme,
  titleBn: s.titleBn,
  titleEn: s.titleEn,
  shortDescBn: s.shortDescBn,
  shortDescEn: s.shortDescEn,
  documentsBn: s.documentsBn,
  documentsEn: s.documentsEn,
}));

const destinationSummaries = destinationsData.map((d) => ({
  slug: d.slug,
  imageKey: d.imageKey,
  featuredOnHome: d.featuredOnHome,
  nameBn: d.nameBn,
  nameEn: d.nameEn,
  regionBn: d.regionBn,
  regionEn: d.regionEn,
  taglineBn: d.taglineBn,
  taglineEn: d.taglineEn,
  startingPriceBDT: d.startingPriceBDT,
  documentsSummaryBn: d.documentsSummaryBn,
  documentsSummaryEn: d.documentsSummaryEn,
}));

const packageSummaries = tourPackagesData.map((p) => ({
  slug: p.slug,
  imageKey: p.imageKey,
  featuredOnHome: p.featuredOnHome,
  category: p.category,
  budgetTier: p.budgetTier,
  countrySlug: p.countrySlug,
  titleBn: p.titleBn,
  titleEn: p.titleEn,
  durationBn: p.durationBn,
  durationEn: p.durationEn,
  priceBDT: p.priceBDT,
  summaryBn: p.summaryBn,
  summaryEn: p.summaryEn,
  hotelTierBn: p.hotelTierBn,
  hotelTierEn: p.hotelTierEn,
  visaIncluded: p.visaIncluded,
  flightIncluded: p.flightIncluded,
}));

const blogSummaries = blogPostsData.map((b) => ({
  slug: b.slug,
  titleBn: b.titleBn,
  titleEn: b.titleEn,
  categoryBn: b.categoryBn,
  categoryEn: b.categoryEn,
}));

const out = `/* eslint-disable */
// AUTO-GENERATED by scripts/generate-catalog-summary.mjs — DO NOT EDIT MANUALLY.
// Re-run "npm run catalog:sync" after editing data modules.
import type { SiteImageKey } from '../config/images';
import type { ServiceIconName } from '../data/services';
import type { PackageCategory, BudgetTier } from '../data/packages';

export interface ServiceSummary {
  slug: string;
  icon: ServiceIconName;
  theme?: 'default' | 'hajj';
  titleBn: string;
  titleEn: string;
  shortDescBn: string;
  shortDescEn: string;
  documentsBn: string[];
  documentsEn: string[];
}

export interface DestinationSummary {
  slug: string;
  imageKey: SiteImageKey;
  featuredOnHome: boolean;
  nameBn: string;
  nameEn: string;
  regionBn: string;
  regionEn: string;
  taglineBn: string;
  taglineEn: string;
  startingPriceBDT: number | null;
  documentsSummaryBn: string[];
  documentsSummaryEn: string[];
}

export interface PackageSummary {
  slug: string;
  imageKey: SiteImageKey;
  featuredOnHome: boolean;
  category: PackageCategory;
  budgetTier: BudgetTier;
  countrySlug: string;
  titleBn: string;
  titleEn: string;
  durationBn: string;
  durationEn: string;
  priceBDT: number | null;
  summaryBn: string;
  summaryEn: string;
  hotelTierBn: string;
  hotelTierEn: string;
  visaIncluded: boolean;
  flightIncluded: boolean;
}

export interface BlogSummary {
  slug: string;
  titleBn: string;
  titleEn: string;
  categoryBn: string;
  categoryEn: string;
}

export const serviceSummaries: ServiceSummary[] = ${JSON.stringify(serviceSummaries, null, 2)};

export const destinationSummaries: DestinationSummary[] = ${JSON.stringify(destinationSummaries, null, 2)};

export const packageSummaries: PackageSummary[] = ${JSON.stringify(packageSummaries, null, 2)};

export const blogSummaries: BlogSummary[] = ${JSON.stringify(blogSummaries, null, 2)};

export function getServiceSummaryBySlug(slug: string): ServiceSummary | undefined {
  return serviceSummaries.find((s) => s.slug === slug);
}

export function getDestinationSummaryBySlug(slug: string): DestinationSummary | undefined {
  return destinationSummaries.find((d) => d.slug === slug);
}

export function getPackageSummaryBySlug(slug: string): PackageSummary | undefined {
  return packageSummaries.find((p) => p.slug === slug);
}

export function getBlogSummaryBySlug(slug: string): BlogSummary | undefined {
  return blogSummaries.find((b) => b.slug === slug);
}
`;

const targetPath = path.resolve(import.meta.dirname, '../src/data/catalogSummary.ts');
fs.writeFileSync(targetPath, out, 'utf8');
console.log(
  `Generated ${targetPath} (${(Buffer.byteLength(out, 'utf8') / 1024).toFixed(1)} KB)`
);
