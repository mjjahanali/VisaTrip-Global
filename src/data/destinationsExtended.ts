interface ExtendedCountrySeed {
  slug: string;
  imageKey: DestinationItem['imageKey'];
  nameBn: string;
  nameEn: string;
  shortNameBn: string;
  shortNameEn: string;
  regionEn: RegionKey;
  taglineBn: string;
  taglineEn: string;
  availableServices: string[];
  bestTimeBn: string;
  bestTimeEn: string;
  processingTimeBn: string;
  processingTimeEn: string;
  overviewBn: string;
  overviewEn: string;
  highlightsBn: string[];
  highlightsEn: string[];
  docProfile: DocProfile;
  faqQBn: string;
  faqABn: string;
  faqQEn: string;
  faqAEn: string;
  primaryKeyword: string;
}

function buildDestination(seed: ExtendedCountrySeed): DestinationItem {
  const docs = getDocumentsByProfile(seed.docProfile);
  const titleBn = `${seed.shortNameBn} ভিসা ও ভ্রমণ গাইড | Visatrip Global`;
  const titleEn = `${seed.shortNameEn} Visa & Travel Guide | Visatrip Global`;
  const descriptionBn = `বাংলাদেশ থেকে ${seed.shortNameBn} ভিসা ডকুমেন্ট, প্রসেসিং সময়, Air Ticket ও ভ্রমণ পরামর্শ — সৎ ও স্বচ্ছ গাইডলাইন | Visatrip Global।`;
  const descriptionEn = `${seed.shortNameEn} visa requirements, document checklist, processing timeline, flights, and travel guidance from Bangladesh with Visatrip Global.`;

  return {
    slug: seed.slug,
    imageKey: seed.imageKey,
    featuredOnHome: false,
    nameBn: seed.nameBn,
    nameEn: seed.nameEn,
    regionBn: REGION_BN_MAP[seed.regionEn],
    regionEn: seed.regionEn,
    taglineBn: seed.taglineBn,
    taglineEn: seed.taglineEn,
    startingPriceBDT: null,
    availableServices: seed.availableServices,
    bestTimeBn: seed.bestTimeBn,
    bestTimeEn: seed.bestTimeEn,
    processingTimeBn: seed.processingTimeBn,
    processingTimeEn: seed.processingTimeEn,
    overviewBn: seed.overviewBn,
    overviewEn: seed.overviewEn,
    highlightsBn: seed.highlightsBn,
    highlightsEn: seed.highlightsEn,
    documentsSummaryBn: docs.bn,
    documentsSummaryEn: docs.en,
    seo: {
      titleBn: titleBn.length <= 60 ? titleBn : `${seed.shortNameBn} ভিসা গাইড | Visatrip Global`,
      descriptionBn,
      titleEn: titleEn.length <= 60 ? titleEn : `${seed.shortNameEn} Visa Guide | Visatrip Global`,
      descriptionEn,
      primaryKeyword: seed.primaryKeyword,
    },
    faqs: [
      {
        questionBn: seed.faqQBn,
        answerBn: seed.faqABn,
        questionEn: seed.faqQEn,
        answerEn: seed.faqAEn,
      },
      {
        questionBn: `Visatrip Global কি ${seed.shortNameBn} ভিসা ফাইল ও Air Ticket একসাথে সহায়তা করে?`,
        answerBn: `হ্যাঁ, আমরা ${seed.shortNameBn}-এর ডকুমেন্ট চেকলিস্ট যাচাই, ফর্ম ও Itinerary প্রস্তুতি, হোটেল বুকিং এবং Air Ticket সাপোর্ট একসাথে প্রদান করি। ভিসা সিদ্ধান্ত সংশ্লিষ্ট Embassy বা ইমিগ্রেশন কর্তৃপক্ষের।`,
        questionEn: `Does Visatrip Global assist with both ${seed.shortNameEn} visa files and flights?`,
        answerEn: `Yes, we support document verification, application preparation, hotel bookings, and air tickets for ${seed.shortNameEn}. Final visa approval rests strictly with the Embassy or immigration authority.`,
      },
    ],
  };
}

